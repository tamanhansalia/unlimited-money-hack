// Builds src/css/icons.generated.css: a subset of the Phosphor icon font CSS containing only the
// icon names that appear in src/**/*.{js,html}. Run automatically before `vite build`.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', '@phosphor-icons', 'web', 'src');

function codepoints(weight) {
  const css = readFileSync(join(pkg, weight, 'style.css'), 'utf8');
  const map = new Map();
  for (const m of css.matchAll(/\.ph(?:-fill)?\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"([^"]+)"/g)) map.set(m[1], m[2]);
  return map;
}
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const file = join(dir, name);
    if (statSync(file).isDirectory()) walk(file, out);
    else if (/\.(js|html)$/.test(name)) out.push(file);
  }
  return out;
}

const regular = codepoints('regular');
const fill = codepoints('fill');
const used = new Set();
for (const file of walk(join(root, 'src'))) {
  for (const word of readFileSync(file, 'utf8').matchAll(/[a-z][a-z0-9]*(?:-[a-z0-9]+)*/g)) {
    used.add(word[0]);
    if (word[0].startsWith('ph-')) used.add(word[0].slice(3)); // class="ph ph-name"
  }
}
const names = [...regular.keys()].filter(name => used.has(name)).sort();
const fillNames = [...fill.keys()].filter(name => used.has(name)).sort();

const css = `/* Generated by scripts/icons.mjs. Do not edit. */
@font-face { font-family: "Phosphor"; src: url("@phosphor-icons/web/regular/Phosphor.woff2") format("woff2"); font-weight: normal; font-style: normal; font-display: block; }
@font-face { font-family: "Phosphor Fill"; src: url("@phosphor-icons/web/fill/Phosphor-Fill.woff2") format("woff2"); font-weight: normal; font-style: normal; font-display: block; }
.ph, .ph-fill { font-style: normal; font-weight: normal; font-variant: normal; line-height: 1; text-transform: none; display: inline-block; flex: none; -webkit-font-smoothing: antialiased; }
.ph { font-family: "Phosphor"; }
.ph-fill { font-family: "Phosphor Fill"; }
${names.map(n => `.ph-${n}::before{content:"${regular.get(n)}"}`).join('\n')}
${fillNames.map(n => `.ph-fill.ph-${n}::before{content:"${fill.get(n)}"}`).join('\n')}
`;
writeFileSync(join(root, 'src', 'css', 'icons.generated.css'), css);
console.log(`icons: ${names.length} regular, ${fillNames.length} fill`);
